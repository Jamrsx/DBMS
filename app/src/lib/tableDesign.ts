/**
 * The table designer's model: columns and indexes as plain choices ("Whole number", "Text up
 * to 255"), turned into the SQL that makes or changes the table. Nothing runs here; the
 * designer shows the SQL and runs it only when asked.
 */
import type { ColumnInfo, DbEngine } from "./db";

export type Kind = "text" | "longtext" | "int" | "bigint" | "decimal" | "bool" | "date" | "datetime" | "json" | "other";

export const KINDS: { kind: Kind; label: string }[] = [
  { kind: "text", label: "Text (short)" },
  { kind: "longtext", label: "Text (long)" },
  { kind: "int", label: "Whole number" },
  { kind: "bigint", label: "Big whole number" },
  { kind: "decimal", label: "Decimal (money, prices)" },
  { kind: "bool", label: "Yes / no" },
  { kind: "date", label: "Date" },
  { kind: "datetime", label: "Date and time" },
  { kind: "json", label: "JSON" },
  { kind: "other", label: "Other (type it)" },
];

export interface ColDraft {
  /** Its name in the database now; missing for a new column. */
  orig?: string;
  name: string;
  kind: Kind;
  /** Text length ("255") or decimal digits ("10,2"). */
  size: string;
  /** The SQL type, for "other" and for types the designer leaves as they are. */
  raw: string;
  nullable: boolean;
  /** Default value as typed; empty means none. */
  def: string;
  primary: boolean;
  autoInc: boolean;
  removed?: boolean;
}

export interface IndexDraft {
  /** Its name in the database now; missing for a new index. */
  orig?: string;
  name: string;
  columns: string[];
  unique: boolean;
  primary?: boolean;
  removed?: boolean;
}

const q = (engine: DbEngine, name: string) =>
  engine === "postgres" ? `"${name.replace(/"/g, '""')}"` : `\`${name.replace(/`/g, "``")}\``;

/** A name the designer accepts: letters, digits, _ and $, not starting with a digit. */
export function nameProblem(name: string): string | null {
  if (!name.trim()) return "Give it a name.";
  if (!/^[A-Za-z_][A-Za-z0-9_$]*$/.test(name))
    return "Use letters, numbers and _, starting with a letter, like created_at.";
  if (name.length > 63) return "Keep names to 63 characters.";
  return null;
}

/** Reads an existing column into the designer's terms. */
export function fromColumn(c: ColumnInfo, engine: DbEngine): ColDraft {
  const t = c.column_type.toLowerCase();
  const sizeOf = () => t.match(/\(([^)]*)\)/)?.[1] ?? "";
  let kind: Kind = "other";
  let size = "";
  if (/^(varchar|character varying)/.test(t)) {
    kind = "text";
    size = sizeOf() || "255";
  } else if (/^(text|mediumtext|longtext)$/.test(t)) kind = "longtext";
  else if (/^(tinyint\(1\)|boolean|bool)/.test(t)) kind = "bool";
  else if (/^(int|integer|int4|smallint|mediumint|tinyint)/.test(t) && !t.startsWith("tinyint(1)")) kind = "int";
  else if (/^(bigint|int8)/.test(t)) kind = "bigint";
  else if (/^(decimal|numeric)/.test(t)) {
    kind = "decimal";
    size = sizeOf() || "10,2";
  } else if (t === "date") kind = "date";
  else if (/^(datetime|timestamp)/.test(t)) kind = "datetime";
  else if (/^jsonb?$/.test(t)) kind = "json";
  const autoInc = /auto_increment/i.test(c.extra) || /nextval\(|identity/i.test(`${c.default ?? ""} ${c.extra}`);
  const def = autoInc ? "" : cleanDefault(c.default);
  return {
    orig: c.name,
    name: c.name,
    kind,
    size,
    raw: c.column_type,
    nullable: c.nullable,
    def,
    primary: c.key === "PRI",
    autoInc,
  };
  void engine;
}

/** PostgreSQL keeps defaults as SQL ('abc'::character varying); show just the value. */
function cleanDefault(d: string | null): string {
  if (d == null) return "";
  const m = d.match(/^'(.*)'::[\w\s]+$/);
  return m ? m[1].replace(/''/g, "'") : d;
}

/** The SQL type for a column. */
export function typeSql(c: ColDraft, engine: DbEngine): string {
  const pg = engine === "postgres";
  switch (c.kind) {
    case "text":
      return `VARCHAR(${c.size.trim() || "255"})`;
    case "longtext":
      return "TEXT";
    case "int":
      return pg && c.autoInc ? "INTEGER GENERATED BY DEFAULT AS IDENTITY" : pg ? "INTEGER" : "INT";
    case "bigint":
      return pg && c.autoInc ? "BIGINT GENERATED BY DEFAULT AS IDENTITY" : "BIGINT";
    case "decimal":
      return `DECIMAL(${c.size.trim() || "10,2"})`;
    case "bool":
      return pg ? "BOOLEAN" : "TINYINT(1)";
    case "date":
      return "DATE";
    case "datetime":
      return pg ? "TIMESTAMP" : "DATETIME";
    case "json":
      return pg ? "JSONB" : "JSON";
    default:
      return c.raw.trim() || "TEXT";
  }
}

/** The default as SQL: numbers, true/false and CURRENT_TIMESTAMP as they are; text quoted. */
function defaultSql(c: ColDraft, engine: DbEngine): string | null {
  const d = c.def.trim();
  if (!d) return null;
  if (/^null$/i.test(d)) return "NULL";
  if (/^(current_timestamp|now\(\))$/i.test(d)) return "CURRENT_TIMESTAMP";
  if (c.kind === "bool") {
    const yes = /^(1|true|yes)$/i.test(d);
    return engine === "postgres" ? (yes ? "TRUE" : "FALSE") : yes ? "1" : "0";
  }
  if (["int", "bigint", "decimal"].includes(c.kind) && /^-?\d+(\.\d+)?$/.test(d)) return d;
  return `'${d.replace(/'/g, "''")}'`;
}

/** One column's definition, as in CREATE TABLE. */
function columnSql(c: ColDraft, engine: DbEngine, withKey: boolean): string {
  const parts = [q(engine, c.name), typeSql(c, engine)];
  parts.push(c.nullable && !c.primary ? "NULL" : "NOT NULL");
  if (c.autoInc && engine === "mysql") parts.push("AUTO_INCREMENT");
  const d = defaultSql(c, engine);
  if (d && !c.autoInc) parts.push(`DEFAULT ${d}`);
  if (withKey && c.primary) parts.push("PRIMARY KEY");
  return parts.join(" ");
}

/** CREATE TABLE for a new table. */
export function createSql(table: string, cols: ColDraft[], engine: DbEngine): string {
  const live = cols.filter((c) => !c.removed);
  const keys = live.filter((c) => c.primary);
  const single = keys.length === 1;
  const lines = live.map((c) => `  ${columnSql(c, engine, single)}`);
  if (keys.length > 1) lines.push(`  PRIMARY KEY (${keys.map((k) => q(engine, k.name)).join(", ")})`);
  return `CREATE TABLE ${q(engine, table)} (\n${lines.join(",\n")}\n);`;
}

function same(a: ColDraft, b: ColDraft, engine: DbEngine) {
  return (
    typeSql(a, engine).toLowerCase() === typeSql(b, engine).toLowerCase() &&
    a.nullable === b.nullable &&
    (defaultSql(a, engine) ?? "") === (defaultSql(b, engine) ?? "")
  );
}

/** The statements that turn the table's current columns into the drafts, in a safe order. */
export function alterSql(table: string, before: ColDraft[], drafts: ColDraft[], engine: DbEngine): string[] {
  const t = q(engine, table);
  const out: string[] = [];
  const pg = engine === "postgres";
  for (const d of drafts) {
    if (d.orig && d.removed) out.push(`ALTER TABLE ${t} DROP COLUMN ${q(engine, d.orig)};`);
  }
  for (const d of drafts) {
    if (d.removed) continue;
    const was = before.find((b) => b.name === d.orig);
    if (!was) {
      out.push(`ALTER TABLE ${t} ADD COLUMN ${columnSql({ ...d, primary: false }, engine, false)};`);
      continue;
    }
    const renamed = was.name !== d.name;
    const changed = !same(was, d, engine);
    if (!renamed && !changed) continue;
    if (!pg) {
      // MySQL changes name, type, NULL and default in one statement.
      const verb = renamed ? `CHANGE COLUMN ${q(engine, was.name)}` : "MODIFY COLUMN";
      out.push(`ALTER TABLE ${t} ${verb} ${columnSql({ ...d, primary: false }, engine, false)};`);
      continue;
    }
    if (renamed) out.push(`ALTER TABLE ${t} RENAME COLUMN ${q(engine, was.name)} TO ${q(engine, d.name)};`);
    const col = q(engine, d.name);
    if (typeSql(was, engine).toLowerCase() !== typeSql(d, engine).toLowerCase())
      out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${typeSql(d, engine)} USING ${col}::${typeSql(d, engine)};`);
    if (was.nullable !== d.nullable)
      out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${d.nullable ? "DROP NOT NULL" : "SET NOT NULL"};`);
    const oldDefault = defaultSql(was, engine) ?? "";
    const newDefault = defaultSql(d, engine) ?? "";
    if (oldDefault !== newDefault)
      out.push(
        newDefault
          ? `ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${newDefault};`
          : `ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT;`,
      );
  }
  return out;
}

/** Statements for index changes: removed ones dropped, new ones made. */
export function indexSql(table: string, indexes: IndexDraft[], engine: DbEngine): string[] {
  const t = q(engine, table);
  const out: string[] = [];
  for (const i of indexes) {
    if (i.orig && i.removed && !i.primary)
      out.push(engine === "postgres" ? `DROP INDEX ${q(engine, i.orig)};` : `DROP INDEX ${q(engine, i.orig)} ON ${t};`);
  }
  for (const i of indexes) {
    if (i.orig || i.removed || i.columns.length === 0) continue;
    out.push(
      `CREATE ${i.unique ? "UNIQUE " : ""}INDEX ${q(engine, i.name)} ON ${t} (${i.columns.map((c) => q(engine, c)).join(", ")});`,
    );
  }
  return out;
}

/** SQL that lists a table's indexes, one row per index column. */
export function listIndexesSql(table: string, engine: DbEngine): string {
  if (engine === "postgres")
    return `SELECT i.relname AS name, a.attname AS column_name, ix.indisunique AS is_unique, ix.indisprimary AS is_primary
FROM pg_class t JOIN pg_index ix ON t.oid = ix.indrelid JOIN pg_class i ON i.oid = ix.indexrelid
JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(ix.indkey)
WHERE t.relname = '${table.replace(/'/g, "''")}' ORDER BY i.relname, array_position(ix.indkey, a.attnum);`;
  return `SHOW INDEX FROM ${q(engine, table)};`;
}

/** Turns the rows of listIndexesSql into indexes. */
export function readIndexes(columns: string[], rows: (string | number | null)[][], engine: DbEngine): IndexDraft[] {
  const col = (n: string) => columns.findIndex((c) => c.toLowerCase() === n.toLowerCase());
  const out: IndexDraft[] = [];
  for (const r of rows) {
    const name = String(r[col(engine === "postgres" ? "name" : "Key_name")]);
    const column = String(r[col(engine === "postgres" ? "column_name" : "Column_name")]);
    const unique =
      engine === "postgres"
        ? ["t", "true", "1"].includes(String(r[col("is_unique")]).toLowerCase())
        : String(r[col("Non_unique")]) === "0";
    const primary =
      engine === "postgres"
        ? ["t", "true", "1"].includes(String(r[col("is_primary")]).toLowerCase())
        : name === "PRIMARY";
    const found = out.find((i) => i.name === name);
    if (found) found.columns.push(column);
    else out.push({ orig: name, name, columns: [column], unique, primary });
  }
  return out;
}

/** Does the plan delete anything (columns or their data)? */
export function dropsData(drafts: ColDraft[], before: ColDraft[]): string[] {
  const dropped = drafts.filter((d) => d.orig && d.removed).map((d) => d.orig!);
  const narrowed = drafts
    .filter((d) => !d.removed && d.orig)
    .filter((d) => {
      const was = before.find((b) => b.name === d.orig);
      return !!was && was.kind !== d.kind && was.kind !== "other";
    })
    .map((d) => d.name);
  return [...dropped, ...narrowed];
}

