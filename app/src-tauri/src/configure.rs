//! Generates DevManager's own config files under `<install root>\etc` and runs the one-time
//! MySQL setup. Vendor config files are never edited, so configs can always be regenerated.

use std::fs;
use std::io::{self, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

/// Port php-cgi listens on for FastCGI requests from Apache or nginx.
pub const PHP_FASTCGI_PORT: u16 = 9085;

/// Extensions most PHP projects (Laravel, WordPress, Symfony) need.
const PHP_EXTENSIONS: &[&str] = &[
    "curl", "fileinfo", "gd", "intl", "mbstring", "exif", "mysqli", "openssl", "pdo_mysql",
    "pdo_sqlite", "sqlite3", "sodium", "zip",
];

/// Settings changed from PHP's defaults for local development.
const PHP_SETTINGS: &[(&str, &str)] = &[
    ("memory_limit", "512M"),
    ("upload_max_filesize", "64M"),
    ("post_max_size", "64M"),
    ("max_execution_time", "120"),
];

/// Forward-slash path for config files (Apache, nginx and MySQL all accept it on Windows).
pub fn conf_path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// php.ini built from the version's own `php.ini-development` (or a minimal one if it's missing),
/// with `extension_dir` pointing at this PHP, common extensions on, and dev-friendly limits.
pub fn php_ini(php_dir: &Path) -> String {
    let template = fs::read_to_string(php_dir.join("php.ini-development")).unwrap_or_default();
    let ext_dir = php_dir.join("ext");
    let available: Vec<&str> = PHP_EXTENSIONS
        .iter()
        .copied()
        .filter(|name| ext_dir.join(format!("php_{name}.dll")).is_file())
        .collect();
    render_php_ini(&template, &ext_dir, &available)
}

pub fn render_php_ini(template: &str, ext_dir: &Path, extensions: &[&str]) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut enabled: Vec<&str> = Vec::new();
    let mut ext_dir_set = false;
    let mut settings_set: Vec<&str> = Vec::new();

    for line in template.lines() {
        let trimmed = line.trim_start_matches(';').trim();
        let key = trimmed.split('=').next().unwrap_or("").trim();
        if key == "extension_dir" && !ext_dir_set && trimmed.contains("\"ext\"") {
            out.push(format!("extension_dir = \"{}\"", conf_path(ext_dir)));
            ext_dir_set = true;
        } else if key == "extension" {
            let name = trimmed.split('=').nth(1).unwrap_or("").split(';').next().unwrap_or("").trim();
            if let Some(ext) = extensions.iter().find(|e| **e == name) {
                if !enabled.contains(ext) {
                    out.push(format!("extension={ext}"));
                    enabled.push(ext);
                }
            } else {
                out.push(line.to_string());
            }
        } else if let Some((k, v)) =
            PHP_SETTINGS.iter().find(|(k, _)| *k == key && !line.trim_start().starts_with(';'))
        {
            out.push(format!("{k} = {v}"));
            settings_set.push(k);
        } else {
            out.push(line.to_string());
        }
    }

    // Anything the template didn't have (or no template at all).
    let mut extra = vec![String::new(), "; Added by DevManager".to_string()];
    if !ext_dir_set {
        extra.push(format!("extension_dir = \"{}\"", conf_path(ext_dir)));
    }
    for ext in extensions.iter().filter(|e| !enabled.contains(e)) {
        extra.push(format!("extension={ext}"));
    }
    for (k, v) in PHP_SETTINGS.iter().filter(|(k, _)| !settings_set.contains(k)) {
        extra.push(format!("{k} = {v}"));
    }
    if extra.len() > 2 {
        out.extend(extra);
    }
    out.join("\r\n") + "\r\n"
}

pub struct ApacheConf<'a> {
    pub server_root: &'a Path,
    pub port: u16,
    pub www_dir: &'a Path,
    pub etc_dir: &'a Path,
    pub logs_dir: &'a Path,
    pub php: bool,
    pub fcgi_port: u16,
}

const APACHE_MODULES: &[&str] = &[
    "alias", "authz_core", "authz_host", "autoindex", "dir", "env", "headers", "log_config", "mime",
    "proxy", "proxy_fcgi", "rewrite", "setenvif",
];

pub fn apache_conf(c: &ApacheConf) -> String {
    let modules: String = APACHE_MODULES
        .iter()
        .map(|m| format!("LoadModule {m}_module modules/mod_{m}.so\n"))
        .collect();
    let php = if c.php {
        // The trailing slash matters on Windows: without it Apache appends the script path's
        // drive letter ("C:") to the port and fails with a DNS lookup error.
        // php-cgi needs a plain Windows path in SCRIPT_FILENAME; the proxy URL form gives it
        // "/C:/..." (or "proxy:fcgi://..."), so build it from the document root instead.
        format!(
            "<FilesMatch \"\\.php$\">\n    SetHandler \"proxy:fcgi://127.0.0.1:{}/\"\n</FilesMatch>\nProxyFCGISetEnvIf \"true\" SCRIPT_FILENAME \"%{{DOCUMENT_ROOT}}%{{reqenv:SCRIPT_NAME}}\"\n"
        , c.fcgi_port)
    } else {
        String::new()
    };
    format!(
        r#"# Generated by DevManager. Changes here are overwritten; edit DevManager's settings instead.
ServerRoot "{root}"
# Keep the PID file in DevManager's folder, never in the Apache install (it may be shared).
PidFile "{logs}/httpd.pid"
Listen {port}
ServerName localhost:{port}

{modules}
TypesConfig conf/mime.types
DirectoryIndex index.php index.html index.htm

ErrorLog "{logs}/apache_error.log"
LogLevel warn
LogFormat "%h %l %u %t \"%r\" %>s %b" common
CustomLog "{logs}/apache_access.log" common

<Directory />
    AllowOverride None
    Require all denied
</Directory>

DocumentRoot "{www}"
<Directory "{www}">
    Options Indexes FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>

{php}
IncludeOptional "{etc}/apache/sites-enabled/*.conf"
"#,
        root = conf_path(c.server_root),
        port = c.port,
        logs = conf_path(c.logs_dir),
        www = conf_path(c.www_dir),
        etc = conf_path(c.etc_dir),
    )
}

pub struct NginxConf<'a> {
    pub nginx_dir: &'a Path,
    pub port: u16,
    pub www_dir: &'a Path,
    pub etc_dir: &'a Path,
    pub logs_dir: &'a Path,
    pub temp_dir: &'a Path,
    pub php: bool,
    pub fcgi_port: u16,
}

pub fn nginx_conf(c: &NginxConf) -> String {
    let nginx = conf_path(c.nginx_dir);
    let temp = conf_path(c.temp_dir);
    let php = if c.php {
        format!(
            r#"
        location ~ \.php$ {{
            fastcgi_pass 127.0.0.1:{};
            fastcgi_index index.php;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            include "{nginx}/conf/fastcgi_params";
        }}"#
        , c.fcgi_port)
    } else {
        String::new()
    };
    format!(
        r#"# Generated by DevManager. Changes here are overwritten; edit DevManager's settings instead.
worker_processes 1;
error_log "{logs}/nginx_error.log";
pid "{temp}/nginx.pid";

events {{
    worker_connections 1024;
}}

http {{
    include "{nginx}/conf/mime.types";
    default_type application/octet-stream;
    sendfile on;
    client_max_body_size 64m;
    access_log "{logs}/nginx_access.log";

    client_body_temp_path "{temp}/client_body";
    proxy_temp_path "{temp}/proxy";
    fastcgi_temp_path "{temp}/fastcgi";
    uwsgi_temp_path "{temp}/uwsgi";
    scgi_temp_path "{temp}/scgi";

    server {{
        listen {port};
        server_name localhost;
        root "{www}";
        index index.php index.html index.htm;
        autoindex on;
{php}
    }}

    include "{etc}/nginx/sites-enabled/*.conf";
}}
"#,
        logs = conf_path(c.logs_dir),
        port = c.port,
        www = conf_path(c.www_dir),
        etc = conf_path(c.etc_dir),
    )
}

pub struct MysqlConf<'a> {
    pub base_dir: &'a Path,
    pub data_dir: &'a Path,
    pub port: u16,
    pub logs_dir: &'a Path,
}

pub fn mysql_ini(c: &MysqlConf) -> String {
    format!(
        r#"# Generated by DevManager. Changes here are overwritten; edit DevManager's settings instead.
[mysqld]
basedir="{base}"
datadir="{data}"
port={port}
# Only this PC can connect.
bind-address=127.0.0.1
mysqlx=OFF
character-set-server=utf8mb4
log-error="{logs}/mysql_error.log"

[client]
port={port}
default-character-set=utf8mb4
"#,
        base = conf_path(c.base_dir),
        data = conf_path(c.data_dir),
        port = c.port,
        logs = conf_path(c.logs_dir),
    )
}

/// Validates an Apache config with `httpd -t`, returning Apache's message on failure.
pub fn check_apache(server_root: &Path, conf: &Path) -> Result<(), String> {
    let httpd = server_root.join("bin").join("httpd.exe");
    let out = run_quiet(&httpd, &["-t", "-f", &conf.display().to_string()], Duration::from_secs(30))
        .map_err(|err| format!("Couldn't run Apache to check its config: {err}"))?;
    if out.success { Ok(()) } else { Err(format!("Apache rejected the config: {}", out.text.trim())) }
}

/// Validates an nginx config with `nginx -t`, returning nginx's message on failure.
pub fn check_nginx(nginx_dir: &Path, conf: &Path) -> Result<(), String> {
    let nginx = nginx_dir.join("nginx.exe");
    let prefix = format!("{}/", conf_path(nginx_dir));
    let out = run_quiet(&nginx, &["-t", "-p", &prefix, "-c", &conf_path(conf)], Duration::from_secs(30))
        .map_err(|err| format!("Couldn't run nginx to check its config: {err}"))?;
    if out.success { Ok(()) } else { Err(format!("nginx rejected the config: {}", out.text.trim())) }
}

pub enum MysqlSetup {
    Initialized,
    /// The data folder already had databases, so it was left alone.
    KeptExisting,
}

/// Creates a fresh data folder and, if given, sets the root password. The password only ever
/// travels over the `mysql` client's standard input; it never appears in arguments or on disk.
/// An existing, non-empty data folder is never touched.
pub fn setup_mysql(
    base_dir: &Path,
    ini: &Path,
    data_dir: &Path,
    port: u16,
    password: Option<&str>,
) -> Result<MysqlSetup, String> {
    if data_dir.is_dir() && fs::read_dir(data_dir).map(|mut d| d.next().is_some()).unwrap_or(false) {
        return Ok(MysqlSetup::KeptExisting);
    }
    let mysqld = base_dir.join("bin").join("mysqld.exe");
    let defaults = format!("--defaults-file={}", ini.display());

    let init = run_quiet(&mysqld, &[&defaults, "--initialize-insecure", "--console"], Duration::from_secs(300))
        .map_err(|err| format!("Couldn't start MySQL to create the data folder: {err}"))?;
    if !init.success {
        return Err(format!("MySQL couldn't create the data folder: {}", last_lines(&init.text, 6)));
    }

    let Some(password) = password else {
        return Ok(MysqlSetup::Initialized);
    };

    let mut server = spawn_quiet(&mysqld, &[&defaults, "--console"])
        .map_err(|err| format!("Couldn't start MySQL to set the password: {err}"))?;
    let result = (|| {
        wait_for_port(port, Duration::from_secs(90), &mut server)?;
        let sql = format!(
            "ALTER USER 'root'@'localhost' IDENTIFIED BY '{}';\nSHUTDOWN;\n",
            sql_string(password)
        );
        let client = base_dir.join("bin").join("mysql.exe");
        let port_arg = port.to_string();
        let out = run_with_stdin(
            &client,
            &["--protocol=TCP", "-h", "127.0.0.1", "-P", &port_arg, "-u", "root", "--skip-password"],
            &sql,
            Duration::from_secs(60),
        )
        .map_err(|err| format!("Couldn't run the MySQL client: {err}"))?;
        if !out.success {
            return Err(format!("Setting the root password failed: {}", last_lines(&out.text, 4)));
        }
        wait_for_exit(&mut server, Duration::from_secs(60))
    })();
    if result.is_err() {
        let _ = server.kill();
        let _ = server.wait();
    }
    result.map(|_| MysqlSetup::Initialized)
}

/// Escapes a value for a single-quoted MySQL string literal.
pub fn sql_string(value: &str) -> String {
    value.replace('\\', "\\\\").replace('\'', "''")
}

fn wait_for_port(port: u16, timeout: Duration, server: &mut Child) -> Result<(), String> {
    let deadline = Instant::now() + timeout;
    let addr = std::net::SocketAddr::from(([127, 0, 0, 1], port));
    while Instant::now() < deadline {
        if let Ok(Some(status)) = server.try_wait() {
            return Err(format!("MySQL stopped while starting (exit code {:?}). See mysql_error.log.", status.code()));
        }
        if TcpStream::connect_timeout(&addr, Duration::from_millis(300)).is_ok() {
            return Ok(());
        }
        std::thread::sleep(Duration::from_millis(250));
    }
    Err(format!("MySQL didn't start listening on port {port} in time."))
}

fn wait_for_exit(child: &mut Child, timeout: Duration) -> Result<(), String> {
    let deadline = Instant::now() + timeout;
    while Instant::now() < deadline {
        if let Ok(Some(_)) = child.try_wait() {
            return Ok(());
        }
        std::thread::sleep(Duration::from_millis(200));
    }
    Err("MySQL didn't shut down after setup.".into())
}

pub struct Output {
    pub success: bool,
    pub code: Option<i32>,
    pub text: String,
}

fn command(program: &Path, args: &[&str]) -> Command {
    let mut cmd = Command::new(program);
    cmd.args(args);
    crate::scan::hide_console(&mut cmd);
    cmd
}

fn spawn_quiet(program: &Path, args: &[&str]) -> io::Result<Child> {
    command(program, args).stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null()).spawn()
}

pub fn run_quiet(program: &Path, args: &[&str], timeout: Duration) -> io::Result<Output> {
    run_with_stdin(program, args, "", timeout)
}

/// Runs a program to completion with `input` on stdin, capturing stdout and stderr.
pub fn run_with_stdin(program: &Path, args: &[&str], input: &str, timeout: Duration) -> io::Result<Output> {
    let mut child = command(program, args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    {
        let mut stdin = child.stdin.take().expect("stdin is piped");
        stdin.write_all(input.as_bytes())?;
    }
    // Drain output on threads so a chatty program can't block on a full pipe.
    let mut stdout = child.stdout.take().expect("stdout is piped");
    let mut stderr = child.stderr.take().expect("stderr is piped");
    let out = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = io::Read::read_to_string(&mut stdout, &mut s);
        s
    });
    let err = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = io::Read::read_to_string(&mut stderr, &mut s);
        s
    });
    let deadline = Instant::now() + timeout;
    let status = loop {
        if let Some(status) = child.try_wait()? {
            break status;
        }
        if Instant::now() >= deadline {
            let _ = child.kill();
            let _ = child.wait();
            return Err(io::Error::new(io::ErrorKind::TimedOut, "timed out"));
        }
        std::thread::sleep(Duration::from_millis(50));
    };
    let text = format!("{}{}", out.join().unwrap_or_default(), err.join().unwrap_or_default());
    Ok(Output { success: status.success(), code: status.code(), text })
}

fn last_lines(text: &str, n: usize) -> String {
    let lines: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
    lines[lines.len().saturating_sub(n)..].join(" | ")
}

/// Writes `contents` to `path`, creating parent folders.
pub fn write_file(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|err| format!("Couldn't create {}: {err}", parent.display()))?;
    }
    fs::write(path, contents).map_err(|err| format!("Couldn't write {}: {err}", path.display()))
}

/// Folder containing an executable's `bin` folder, e.g. `...\Apache24` for `...\Apache24\bin\httpd.exe`.
pub fn root_above_bin(exe: &Path) -> Option<PathBuf> {
    let dir = exe.parent()?;
    if dir.file_name()?.eq_ignore_ascii_case("bin") { dir.parent().map(Path::to_path_buf) } else { Some(dir.to_path_buf()) }
}

